# Custom Ricker wavelet function (Mexican hat) - defined manually to avoid import issues
def ricker(points, a):
    """Return a Ricker wavelet (Mexican hat) - standard for ERG analysis."""
    vec = np.arange(-points // 2, points // 2 + 1, dtype=float)
    vec2 = (1 - vec**2 / (a**2 / 2)) * np.exp(-vec**2 / (a**2))
    return vec2 / np.abs(vec2).max()  # Normalized

