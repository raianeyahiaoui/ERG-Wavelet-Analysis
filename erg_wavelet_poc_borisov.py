# Function to extract and analyze one signal column
def analyze_erg_signal(df, signal_col=2, sigma=2.0):
    time_col = 0
    data_guess_start = 6
    potential_data = df.iloc[data_guess_start:, [time_col, signal_col]]
    potential_data = potential_data.apply(pd.to_numeric, errors='coerce')
    potential_data = potential_data.dropna()

    time = potential_data.iloc[:, 0].values.astype(float)
    erg_signal = potential_data.iloc[:, 1].values.astype(float) # Renamed 'signal' to 'erg_signal'

    # Denoise
    denoised = gaussian_filter1d(erg_signal, sigma) # Use erg_signal

    # SNR estimate (refined: use mean signal power vs. noise std)
    noise = erg_signal - denoised # Use erg_signal
    snr = 20 * np.log10(np.mean(np.abs(erg_signal)) / np.std(noise) if np.std(noise) != 0 else np.inf) # Use erg_signal

    # Peak/Valley detection (for oscillatory potentials: adjust height/distance for ERG waves)
    peaks, _ = find_peaks(denoised, height=0.5, distance=5)  # Positive peaks (b-waves/oscillations)
    valleys, _ = find_peaks(-denoised, height=0.5, distance=5)  # Negative (a-waves)

    # Quantitative ERG metrics (example: avg amplitude, latency)
    if len(peaks) > 0 and len(valleys) > 0:
        avg_amp = np.mean(denoised[peaks] - denoised[valleys[:len(peaks)]])  # Peak-to-valley amps
        avg_latency = np.mean(time[peaks])  # Average implicit time
    else:
        avg_amp, avg_latency = 0, 0

    # CWT Scalogram (time-frequency: for detecting frequency-specific patterns) using pywt
    widths = np.arange(1, 31)  # Scales
    cwtmatr, freqs = pywt.cwt(denoised, widths, 'mexh') # Use pywt.cwt with 'mexh' (Mexican Hat) wavelet

    # Energy for pattern detection (high energy = potential abnormalities)
    energy = np.sum(np.abs(cwtmatr)**2, axis=0)
    threshold = np.percentile(energy, 95)
    pattern_indices = np.where(energy > threshold)[0]
    pattern_times = time[pattern_indices]

    # Print metrics
    print(f"Column {signal_col}: SNR = {snr:.2f} dB")
    print(f"Detected {len(peaks)} peaks (times ms): {time[peaks]}")
    print(f"Detected {len(valleys)} valleys (times ms): {time[valleys]}")
    print(f"Avg Oscillation Amplitude: {avg_amp:.2f} µV, Avg Latency: {avg_latency:.2f} ms")
    print(f"High-Energy Patterns at times (ms): {pattern_times}")

    # Plot
    fig, axs = plt.subplots(4, 1, figsize=(12, 16))
    axs[0].plot(time, erg_signal, label='Original') # Use erg_signal
    axs[0].plot(time, denoised, label='Denoised')
    axs[0].set_title(f'ERG Signal (Column {signal_col})')
    axs[0].set_xlabel('Time (ms)')
    axs[0].set_ylabel('Amplitude (µV)')
    axs[0].legend()

    axs[1].plot(time, denoised)
    axs[1].plot(time[peaks], denoised[peaks], 'x', label='Peaks')
    axs[1].plot(time[valleys], denoised[valleys], 'o', label='Valleys')
    axs[1].set_title('Peak/Valley Detection (Oscillatory Potentials)')
    axs[1].legend()

    axs[2].plot(time, energy)
    axs[2].scatter(time[pattern_indices], energy[pattern_indices], color='red')
    axs[2].set_title('Energy Across Scales (Pattern Detection)')

    axs[3].imshow(np.abs(cwtmatr), extent=[time.min(), time.max(), freqs.min(), freqs.max()], cmap='PRGn', aspect='auto')
    axs[3].set_title('Scalogram (CWT - Time-Frequency Analysis)')
    axs[3].set_ylabel('Scale (Higher = Lower Freq)')

    plt.tight_layout()
    plt.show()
    fig.savefig(f'erg_analysis_col{signal_col}.pdf')  # Save for application

